import '../../domain/entities/receiver_user_wallet_entity.dart';

class ReceiverUserWalletModel extends ReceiverUserWalletEntity {
  ReceiverUserWalletModel(
      {required super.id,
      required super.userId,
      required super.balance,
      required super.grossMoney,
      required super.monthlyBalance,
      required super.total,
      required super.months,
      required super.tenYears,
      required super.fiveYears,
      required super.providerCashBack,
      required super.refundStorage,
      required super.freeClickStorage,
      required super.referralStorage,
      required super.referralCashBack,
      required super.shareBalance,
      required super.totalPayment,
      required super.totalCashBack,
      required super.todayGift,
      required super.lastGift,
      required super.totalLikes,
      required super.totalViews,
      required super.totalShares,
      required super.isActive,
      required super.realAmount,
      required super.createdAt,
      required super.updatedAt,
      required super.fiveYearsComplete,
      required super.tenYearsComplete});

  factory ReceiverUserWalletModel.fromJson(Map<String, dynamic> json) {
    return ReceiverUserWalletModel(
      id: json['_id'],
      userId: json['user_id'],
      balance: json['balance'],
      grossMoney: json['gross_money'],
      monthlyBalance: json['monthly_balance'],
      total: json['total'],
      months: json['months'],
      tenYears: json['ten_years'],
      fiveYears: json['five_years'],
      providerCashBack: json['provider_cash_back'].toDouble(),
      refundStorage: json['refund_storage'],
      freeClickStorage: json['free_click_storage'],
      referralStorage: json['referral_storage'],
      referralCashBack: json['referral_cash_back'],
      shareBalance: json['shareBalance'],
      totalPayment: json['total_payment'],
      totalCashBack: json['total_cash_back'],
      todayGift: json['today_gift'],
      lastGift: json['last_gift'],
      totalLikes: json['total_likes'],
      totalViews: json['total_views'],
      totalShares: json['total_shares'],
      isActive: json['isActive'],
      realAmount: json['realAmount'],
      createdAt: DateTime.parse(json['createdAt']),
      updatedAt: DateTime.parse(json['updatedAt']),
      fiveYearsComplete: json['fiveYearsComplete'],
      tenYearsComplete: json['tenYearsComplete'],
    );
  }
}
